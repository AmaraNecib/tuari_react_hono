import { randomUUID } from "node:crypto";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect, it } from "vitest";
import { createDatabaseConnection } from "../../infrastructure/database/factory";
import { createFifoLock } from "../../infrastructure/database/fifo-lock";
import { ensureFreshExperimentalInvoiceSettlementSchema } from "../../infrastructure/database/fresh-experimental-invoice-settlement-schema";
import { ExactFinanceService } from "../company/exact-finance.service";
import { ManualSettlementService } from "../company/manual-settlement.service";
import { SqliteManualSettlementRepository } from "../company/adapters/sqlite-manual-settlement.repository";
import { SqliteExactFinanceRepository } from "../company/adapters/sqlite-exact-finance.repository";
import { SqliteExperimentalInvoiceRepository } from "./adapters/sqlite-exact-invoice.repository";
import { ExperimentalExactInvoiceService } from "./experimental-invoice.service";
import { ExperimentalInvoiceSettlementParticipant } from "./experimental-invoice-settlement-participant";

const party = "00000000-0000-4000-8000-000000000999";
const invoiceId = "00000000-0000-4000-8000-000000000101";
const now = "2026-11-10T00:00:00.000Z";
it("receives an experimental invoice and records actual bank cash against its owned ledger original", async () => {
  const path = join(mkdtempSync(join(tmpdir(), "tuari-615-invoice-service-")), "fixture.sqlite");
  let db = createDatabaseConnection(path, "", { journalMode: "preserve" });
  try {
    await ensureFreshExperimentalInvoiceSettlementSchema(db);
    db.prepare("INSERT INTO external_counterparty(id,full_name,phone_number,note,created_at,updated_at) VALUES (?,?,?,?,?,?)").run(party,"Vendor","",null,now,now);
    const lock = createFifoLock();
    const repository = new SqliteExperimentalInvoiceRepository(db, lock);
    const ledger = new SqliteExactFinanceRepository(db, lock);
    const finance = new ExactFinanceService(ledger, { id: randomUUID, now: () => now });
    const participant = new ExperimentalInvoiceSettlementParticipant(repository, finance, ledger);
    const service = new ExperimentalExactInvoiceService(repository, finance, { id: randomUUID, now: () => now });
    const draft = service.createInvoice({ requestId: "draft", id: invoiceId, counterpartyType: "EXTERNAL_COUNTERPARTY", counterpartyId: party, supplierName: "Vendor", lineItems: [{ description: "Goods", source: { mode: "agreed-total", total: "100.00", quantity: "1" } }] });
    expect(draft).toMatchObject({ status: "DRAFT", totalAmount: "100.00", paidAmount: "0.00", settledAmount: "0.00", remainingAmount: "100.00" });
    expect(participant.lookupOriginal(draft.id)).toBeNull();
    const received = service.receiveInvoice({ requestId: "receive", id: invoiceId });
    expect(received.status).toBe("RECEIVED");
    const payment = service.createPayment({ requestId: "cash", counterpartyType: "EXTERNAL_COUNTERPARTY", counterpartyId: party, direction: "PURCHASE", paymentDate: now, paymentMethod: "BANK_TRANSFER", totalAmount: "20.00", allocations: [{ invoiceId, amount: "20.00" }] });
    expect(payment.unallocatedAmount).toBe("0.00");
    expect(service.getInvoice(invoiceId)).toMatchObject({ status: "RECEIVED", paidAmount: "20.00", settledAmount: "0.00", remainingAmount: "80.00" });
    expect(finance.remaining(received.debtEntryId!)).toBe("80.00");
    expect(participant.validateEligible(received.debtEntryId!)).toMatchObject({ direction: "PAYABLE", invoice: { status: "RECEIVED", paidAmount: "20.00", remainingAmount: "80.00" } });
    expect(participant.lookupOriginal(payment.allocations[0]!.debtEntryId)).toBeNull();
    expect(() => new ExperimentalInvoiceSettlementParticipant(repository, finance, new SqliteExactFinanceRepository(db, createFifoLock()))).toThrow(/same connection and shared FIFO/i);
    const unallocated = service.createPayment({ requestId: "cash-unallocated", counterpartyType: "EXTERNAL_COUNTERPARTY", counterpartyId: party, direction: "PURCHASE", paymentDate: now, paymentMethod: "CHECK", totalAmount: "3.00", allocations: [] });
    expect(unallocated.unallocatedAmount).toBe("3.00");
    service.allocatePayment({ requestId: "allocate-check", id: unallocated.id, allocations: [{ invoiceId, amount: "3.00" }] });
    expect(service.getInvoice(invoiceId)).toMatchObject({ paidAmount: "23.00", settledAmount: "0.00", remainingAmount: "77.00" });
    service.voidPayment({ requestId: "void-check", id: unallocated.id, reason: "test reversal" });
    expect(service.getInvoice(invoiceId)).toMatchObject({ paidAmount: "20.00", settledAmount: "0.00", remainingAmount: "80.00" });
    const manualAccount = finance.createAccount({ requestId: "manual-receivable", partyType: "EXTERNAL_COUNTERPARTY", externalCounterpartyId: party, direction: "RECEIVABLE", openingBalanceDzd: "80.00" });
    const manualOriginalId = ledger.listEntries(manualAccount.id)[0]!.id;
    expect(() => new SqliteManualSettlementRepository(db, createFifoLock(), undefined, participant)).toThrow(/same connection and shared FIFO/i);
    const manualRepository = new SqliteManualSettlementRepository(db, lock, undefined, participant);
    const authorization = { authorize: () => ({ actorUserId: "internal-test-operator", actorLabel: "Internal test" }) };
    const manual = new ManualSettlementService(finance, ledger, manualRepository, authorization, { id: randomUUID, now: () => now }, undefined, participant);
    const payableOriginalId = received.debtEntryId!;
    const previewInput = { externalCounterpartyId: party, payableOriginalEntryId: payableOriginalId, receivableOriginalEntryId: manualOriginalId, currency: "DZD" as const, amountDzd: "80.00" };
    expect(manual.preview(previewInput)).toMatchObject({ payableRemainingDzd: "80.00", receivableRemainingDzd: "80.00", projectedPayableRemainingDzd: "0.00", projectedReceivableRemainingDzd: "0.00" });
    expect(() => manual.preview({ ...previewInput, externalCounterpartyId: randomUUID() })).toThrow(/ineligible/i);
    expect(() => manual.preview({ ...previewInput, payableOriginalEntryId: manualOriginalId })).toThrow(/distinct original obligations/i);
    const normalRepository = new SqliteManualSettlementRepository(db, lock);
    const normal = new ManualSettlementService(finance, ledger, normalRepository, authorization, { id: randomUUID, now: () => now });
    expect(() => normal.preview(previewInput)).toThrow(/ineligible/i);
    expect(finance.remaining(payableOriginalId)).toBe("80.00");
    const confirmInput = { ...previewInput, requestId: "invoice-pair-confirm", expectedPayableRemainingDzd: "80.00", expectedReceivableRemainingDzd: "80.00" };
    const beforePayment = service.listPayments();
    const beforePaymentInvoice = service.getInvoice(invoiceId);
    const aggregateReceiptsBefore = db.prepare("SELECT COUNT(*) AS count FROM exact_finance_command").get();
    const saveReceipt = ledger.saveAggregateCommand.bind(ledger);
    ledger.saveAggregateCommand = () => { throw new Error("Injected aggregate receipt failure"); };
    expect(() => manual.confirm(confirmInput)).toThrow(/Injected aggregate receipt failure/);
    ledger.saveAggregateCommand = saveReceipt;
    expect(finance.remaining(payableOriginalId)).toBe("80.00");
    expect(finance.remaining(manualOriginalId)).toBe("80.00");
    expect(service.getInvoice(invoiceId)).toEqual(beforePaymentInvoice);
    expect(service.listPayments()).toEqual(beforePayment);
    expect(manualRepository.listAccountSettlements(manualAccount.id)).toEqual([]);
    expect(db.prepare("SELECT COUNT(*) AS count FROM exact_finance_command").get()).toEqual(aggregateReceiptsBefore);
    const confirmed = manual.confirm(confirmInput);
    expect(confirmed.settlement.amountDzd).toBe("80.00");
    expect(finance.remaining(payableOriginalId)).toBe("0.00");
    expect(finance.remaining(manualOriginalId)).toBe("0.00");
    expect(service.getInvoice(invoiceId)).toMatchObject({ status: "SETTLED", paidAmount: "20.00", settledAmount: "80.00", remainingAmount: "0.00" });
    expect(service.listPayments()).toEqual(beforePayment);
    expect(manualRepository.listAccountSettlements(manualAccount.id)).toHaveLength(1);
    expect(manual.history({ externalCounterpartyId: party }).items[0]).toMatchObject({ payableSource: { kind: "RESTRICTED" } });
    expect(manual.confirm(confirmInput)).toEqual(confirmed);
    expect(() => manual.confirm({ ...confirmInput, amountDzd: "79.00" })).toThrow(/conflict/i);
    const saleId = "00000000-0000-4000-8000-000000000111";
    const sale = service.createInvoice({ requestId: "sale-draft", id: saleId, counterpartyType: "EXTERNAL_COUNTERPARTY", counterpartyId: party, supplierName: "Vendor", direction: "SALE", lineItems: [{ description: "Sale", source: { mode: "agreed-total", total: "5.00", quantity: "1" } }] });
    expect(sale.direction).toBe("SALE");
    service.receiveInvoice({ requestId: "sale-receive", id: saleId });
    service.createPayment({ requestId: "sale-check", counterpartyType: "EXTERNAL_COUNTERPARTY", counterpartyId: party, direction: "SALE", paymentDate: now, paymentMethod: "CHECK", totalAmount: "5.00", allocations: [{ invoiceId: saleId, amount: "5.00" }] });
    expect(service.getInvoice(saleId)).toMatchObject({ status: "PAID", paidAmount: "5.00", settledAmount: "0.00", remainingAmount: "0.00" });
    const saleSource = participant.lookupOriginal(service.getInvoice(saleId).debtEntryId!);
    expect(saleSource).toMatchObject({ direction: "RECEIVABLE", invoice: { status: "PAID" } });
    expect(() => participant.validateEligible(service.getInvoice(saleId).debtEntryId!)).toThrow(/exhausted/i);
    db.close();
    db = createDatabaseConnection(path, "", { journalMode: "preserve" });
    const reopened = new SqliteExperimentalInvoiceRepository(db, createFifoLock());
    expect(reopened.getInvoice(invoiceId)).toMatchObject({ status: "SETTLED", paidAmount: "20.00", settledAmount: "80.00", remainingAmount: "0.00" });
  } finally { db.close(); }
});
